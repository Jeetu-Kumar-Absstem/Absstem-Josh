function parseCsvLine(line) {
  const out = [];
  let cur = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (ch === '"') {
      const next = line[i + 1];
      if (inQuotes && next === '"') {
        cur += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (ch === "," && !inQuotes) {
      out.push(cur);
      cur = "";
      continue;
    }

    cur += ch;
  }
  out.push(cur);
  return out;
}

function parseCsvText(text) {
  const lines = String(text || "")
    .split(/\r?\n/)
    .filter((line) => line.trim().length);
  if (!lines.length) return [];

  const header = parseCsvLine(lines[0]).map((h) => h.replace(/^\uFEFF/, "").trim());
  const rows = [];

  for (let i = 1; i < lines.length; i += 1) {
    const cols = parseCsvLine(lines[i]);
    const row = {};
    for (let j = 0; j < header.length; j += 1) {
      row[header[j]] = String(cols[j] ?? "").trim();
    }
    rows.push(row);
  }

  return rows;
}

function normalizeTabularRows(rows, { startRow = 2 } = {}) {
  if (!Array.isArray(rows)) return [];
  return rows.map((row, index) => {
    const next = {};
    for (const [key, value] of Object.entries(row || {})) {
      const normalizedKey = String(key || "").replace(/^\uFEFF/, "").trim();
      if (!normalizedKey) continue;
      next[normalizedKey] = value === null || value === undefined ? "" : String(value).trim();
    }
    next.__row_number = startRow + index;
    return next;
  });
}

function pickFirst(source, keys) {
  for (const key of keys) {
    if (Object.prototype.hasOwnProperty.call(source || {}, key)) return source[key];
  }
  return undefined;
}

function findSheetName(workbook, expectedName) {
  const names = Array.isArray(workbook?.SheetNames) ? workbook.SheetNames : [];
  const compact = (value) => String(value || "").trim().toLowerCase().replace(/[\s_-]+/g, "");
  const target = compact(expectedName);
  return names.find((name) => compact(name) === target) || null;
}

function findAnySheetName(workbook, expectedNames) {
  for (const expectedName of expectedNames || []) {
    const match = findSheetName(workbook, expectedName);
    if (match) return match;
  }
  return null;
}

