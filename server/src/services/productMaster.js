          item_name = excluded.item_name,
          item_type = excluded.item_type,
          uom = excluded.uom,
          hsn_no = excluded.hsn_no,
          list_price = excluded.list_price,
          gst_pct = excluded.gst_pct,
          description = excluded.description,
