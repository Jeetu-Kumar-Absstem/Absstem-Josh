async function resolveCompanyReference(client, value) {
  const raw = norm(value);
  if (!raw) return null;
  const simplified = raw.includes("•") ? norm(raw.split("•")[0]) : raw;
  const r = await client.query(
    `
      select
        c.id,
        c.company_code,
        coalesce(cp.company_name, c.company_code) as company_name
      from companies c
      left join company_profiles_v2 cp on cp.company_id = c.id
      where lower(c.company_code) = lower($1)
         or lower(coalesce(cp.company_name, '')) = lower($1)
      order by c.id asc
      limit 1
    `,
    [simplified || raw]
  );
  return r.rows[0] || null;
}

async function resolveVendorReference(client, value) {
  const raw = norm(value);
  if (!raw) return null;
  const simplified = raw.includes("•") ? norm(raw.split("•")[0]) : raw;
  const r = await client.query(
    `
      select
        id,
        vendor_code,
        company_name
      from vendors
      where lower(vendor_code) = lower($1)
         or lower(company_name) = lower($1)
      order by id asc
      limit 1
    `,
    [simplified || raw]
  );
  return r.rows[0] || null;
}

