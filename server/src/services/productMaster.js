  const technicalNotes = norm(pickFirst(payload, ["technical_notes", "technicalNotes", "Technical Notes"]));
  const familyKeys = ["family_key", "FamilyKey", "Family Key", "Family"];
  const moduleKeys = ["module_role", "ModuleRole", "Module Role", "Module"];
  const variantKeys = ["variant_key", "VariantKey", "Variant Key", "Variant"];
  const familyProvided = familyKeys.some((key) => Object.prototype.hasOwnProperty.call(payload, key));
  const moduleProvided = moduleKeys.some((key) => Object.prototype.hasOwnProperty.call(payload, key));
  const variantProvided = variantKeys.some((key) => Object.prototype.hasOwnProperty.call(payload, key));
  const specsProvided =
    Object.prototype.hasOwnProperty.call(payload, "specifications_json") ||
    Object.prototype.hasOwnProperty.call(payload, "specifications");

  let existingRow = null;
  if (existingId) {
    const existingRes = await client.query(
      `
        select item_code, specifications_json, family_key, module_role, variant_key, technical_notes
        from products
        where id = $1
        limit 1
      `,
      [existingId]
    );
    existingRow = existingRes.rows[0] || null;
  }

  let effectiveItemCode = itemCode;
  if (existingId && existingRow?.item_code) {
    const dbItemCode = norm(existingRow.item_code);
    if (dbItemCode) {
      if (itemCode && dbItemCode.toLowerCase() !== itemCode.toLowerCase()) {
        effectiveItemCode = dbItemCode;
      } else if (!itemCode) {
        effectiveItemCode = dbItemCode;
      }
    }
  }

