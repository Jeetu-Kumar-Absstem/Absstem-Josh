function excelColumnName(index) {
  let n = Number(index) || 1;
  let out = "";
  while (n > 0) {
    const rem = (n - 1) % 26;
    out = String.fromCharCode(65 + rem) + out;
    n = Math.floor((n - 1) / 26);
  }
  return out || "A";
}

function addListValidation(worksheet, columnKey, formula, endRow = 1000) {
  for (let row = 2; row <= endRow; row += 1) {
    worksheet.getCell(`${columnKey}${row}`).dataValidation = {
      type: "list",
      allowBlank: true,
      formulae: [formula],
      showErrorMessage: true,
    };
  }
}

function addListValidationByFieldKey(worksheet, fieldKey, formula, endRow = 1000) {
  const index = (worksheet.columns || []).findIndex((column) => column?.key === fieldKey);
  if (index < 0) return;
  addListValidation(worksheet, excelColumnName(index + 1), formula, endRow);
}

