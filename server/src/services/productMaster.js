function comparableUnifiedValue(value) {
  return String(value ?? "").trim().toLowerCase();
}

function parseUnifiedProductMasterRows(rows = []) {
  const productsByCode = new Map();
  const conflicts = [];
  const companyPolicyRows = [];

  for (const row of rows) {
    const productRow = buildUnifiedProductRow(row);
    if (productRow) {
      const itemCode = String(productRow["Item Code"]).trim();
      const key = itemCode.toLowerCase();
      if (!productsByCode.has(key)) {
        productsByCode.set(key, { ...productRow, __row_numbers: [productRow.__row_number].filter(Boolean) });
      } else {
        const existing = productsByCode.get(key);
        for (const [field, incoming] of Object.entries(productRow)) {
          if (field === "__row_number") continue;
          const current = existing[field];
          if (!norm(incoming)) continue;
          if (!norm(current)) {
            existing[field] = incoming;
            continue;
          }
          if (comparableUnifiedValue(current) !== comparableUnifiedValue(incoming)) {
            conflicts.push({
              item_code: itemCode,
              field,
              first_row_number: existing.__row_numbers?.[0] || null,
              conflicting_row_number: productRow.__row_number || null,
              first_value: current,
              conflicting_value: incoming,
            });
            break;
          }
        }
        existing.__row_numbers = Array.from(new Set([...(existing.__row_numbers || []), productRow.__row_number].filter(Boolean)));
      }
    }

    const companyPolicyRow = buildUnifiedCompanyPolicyRow(row);
    if (companyPolicyRow) companyPolicyRows.push(companyPolicyRow);
  }

  if (conflicts.length) {
    const err = new Error("INCONSISTENT_PRODUCT_ROWS");
    err.status = 400;
    err.details = {
      conflict_count: conflicts.length,
      conflicts: conflicts.slice(0, 12),
    };
    throw err;
  }

  const productRows = Array.from(productsByCode.values()).map((row) => {
    const { __row_numbers, ...payload } = row;
    payload.__row_number = __row_numbers?.[0] || row.__row_number || null;
    return payload;
  });

  return {
    product_rows: productRows,
    company_policy_rows: companyPolicyRows,
    row_count: rows.length,
  };
}

function parseProductImportInput(input, filename = "") {
  const ext = String(path.extname(filename || "") || "").toLowerCase();
  if (ext === ".csv") {
    return {
      format: "csv",
      sheet_names: ["Products"],
      product_rows: parseCsvText(Buffer.isBuffer(input) ? input.toString("utf8") : String(input || "")),
      company_policy_rows: [],
      row_count: 0,
    };
  }

  const buffer = Buffer.isBuffer(input) ? input : Buffer.from(String(input || ""), "utf8");
  const workbook = XLSX.read(buffer, { type: "buffer", cellDates: false });
  const unifiedSheetName = findAnySheetName(workbook, UNIFIED_PRODUCT_MASTER_SHEET_NAMES);
  if (unifiedSheetName) {
    const unifiedRows = normalizeTabularRows(XLSX.utils.sheet_to_json(workbook.Sheets[unifiedSheetName], { defval: "", raw: false }), { startRow: 2 });
    const parsedUnified = parseUnifiedProductMasterRows(unifiedRows);
    return {
      format: "xlsx",
      sheet_names: workbook.SheetNames || [],
      product_rows: parsedUnified.product_rows,
      company_policy_rows: parsedUnified.company_policy_rows,
      row_count: parsedUnified.row_count,
    };
  }
  const productsSheetName = findSheetName(workbook, "Products");
  if (!productsSheetName) {
    const err = new Error("PRODUCTS_SHEET_REQUIRED");
    err.status = 400;
    throw err;
  }
  const companyPoliciesSheetName = findSheetName(workbook, "CompanyPolicies");

  const productRows = normalizeTabularRows(
    XLSX.utils.sheet_to_json(workbook.Sheets[productsSheetName], { defval: "", raw: false }),
    { startRow: 2 }
  );
  const companyPolicyRows = companyPoliciesSheetName
    ? normalizeTabularRows(
        XLSX.utils.sheet_to_json(workbook.Sheets[companyPoliciesSheetName], { defval: "", raw: false }),
        { startRow: 2 }
      )
    : [];

  return {
    format: "xlsx",
    sheet_names: workbook.SheetNames || [],
    product_rows: productRows,
    company_policy_rows: companyPolicyRows,
    row_count: productRows.length + companyPolicyRows.length,
  };
}

function toNum(v) {
  const n = Number(String(v ?? "").trim());
  return Number.isFinite(n) ? n : null;
}

function toBool(v) {
  const s = String(v ?? "").trim().toLowerCase();
  if (!s) return null;
  if (["yes", "y", "true", "1"].includes(s)) return true;
  if (["no", "n", "false", "0"].includes(s)) return false;
  return null;
}

function boolLabel(value) {
  if (value === true) return "Yes";
  if (value === false) return "No";
  return "—";
}

function norm(s) {
  const v = String(s ?? "").trim();
  return v || null;
}

function normalizeUom(v) {
  const raw = norm(v);
  if (!raw) return null;
  const s = raw.toLowerCase();
  if (s === "no" || s === "nos" || s === "nos.") return "Nos";
  return raw;
}

function normalizeMfgJobPrefix(v) {
  const raw = norm(v);
  if (!raw) return null;
  const upper = raw.toUpperCase();
  if (upper.startsWith("M ")) return "M";
  if (upper.startsWith("N ")) return "N";
  if (upper.startsWith("ID ")) return "ID";
  if (upper.startsWith("M •")) return "M";
  if (upper.startsWith("N •")) return "N";
  if (upper.startsWith("ID •")) return "ID";
  return ["M", "N", "ID"].includes(upper) ? upper : null;
}

function normalizeFamilyKey(value) {
  const base = norm(value);
  if (!base) return null;
  const raw = base.toUpperCase().replace(/\s+/g, "_");
  if (["NGEN", "NGENX", "MEDO", "MEDO_C", "IDOS", "IDOS_C", "SHIELD"].includes(raw)) return raw;
  return null;
}

function normalizeModuleRole(value) {
  const base = norm(value);
  if (!base) return null;
  const raw = base.toLowerCase().replace(/[\s-]+/g, "_");
  const aliases = {
    generator: "generator",
    air_system: "air_system",
    airsystem: "air_system",
    compressed_air: "air_system",
    gas_storage: "gas_storage",
    storage: "gas_storage",
    storage_vessel: "gas_storage",
    booster: "booster",
    shield: "shield",
    accessory: "accessory",
    spare: "spare",
    spares: "spare",
    other: "other",
  };
  return aliases[raw] || null;
}

function normalizeVariantKey(value) {
  const base = norm(value);
  if (!base) return null;
  const raw = base.toUpperCase().replace(/[\s_-]+/g, "");
  if (["HF", "SH", "UH"].includes(raw)) return raw;
  // Legacy nGEN purity builds, retired by the 12-Mar-2025 rename.
  const legacy = { STD: "STD", PLAIN: "STD", STANDARD: "STD", P: "P", PURITY: "P" };
  return legacy[raw] || null;
}

function mfgJobPrefixLabel(value) {
  const normalized = normalizeMfgJobPrefix(value);
  if (normalized === "M") return "M • Medical Oxygen";
  if (normalized === "N") return "N • Nitrogen";
  if (normalized === "ID") return "ID • Industrial Oxygen";
  return norm(value) || "";
}

function normalizeSourcingMode(v) {
  const raw = norm(v);
  if (!raw) return null;
  const value = raw.toLowerCase();
  if (["manufactured here", "manufactured in this company", "manufactured", "make here"].includes(value)) return "manufacture";
  if (["intercompany sourced", "buy intercompany", "intercompany", "source from partner company"].includes(value)) return "buy_intercompany";
  if (["buy external", "externally sourced", "external purchase", "buy externally"].includes(value)) return "buy_external";
  if (["service only", "service-only"].includes(value)) return "service_only";
  return ["manufacture", "buy_external", "buy_intercompany", "service_only", "blocked"].includes(value) ? value : null;
}

function sourcingModeLabel(value) {
  const normalized = normalizeSourcingMode(value) || String(value || "").trim().toLowerCase();
  if (normalized === "manufacture") return "Manufactured here";
  if (normalized === "buy_intercompany") return "Intercompany sourced";
  if (normalized === "buy_external") return "Buy external";
  if (normalized === "service_only") return "Service only";
  if (normalized === "blocked") return "Blocked";
  return String(value || "").trim() || "Not set";
}

function isRowBlank(row) {
  if (!row || typeof row !== "object") return true;
  return Object.values(row).every((v) => !String(v ?? "").trim().length);
}

function extractAttributes(source) {
  const attrs = [];
  for (let i = 1; i <= 20; i += 1) {
    const caption = norm(source[`Caption${i}`] ?? source[`Caption ${i}`] ?? source[`caption_${i}`]);
    const specValue = norm(source[`Description${i}`] ?? source[`Description ${i}`] ?? source[`spec_value_${i}`]);
    if (!caption && !specValue) continue;
    attrs.push({
      sort_order: i,
      caption,
      spec_value: specValue,
    });
  }

  if (Array.isArray(source.attributes)) {
    return source.attributes
      .map((item, index) => ({
        sort_order: Number(item?.sort_order) || index + 1,
        caption: norm(item?.caption),
        spec_value: norm(item?.spec_value),
      }))
      .filter((item) => item.caption || item.spec_value);
  }

  return attrs;
}

function hasExplicitAttributesPayload(source) {
  if (!source || typeof source !== "object") return false;
  if (Array.isArray(source.attributes)) return true;
  for (let i = 1; i <= 20; i += 1) {
    if (`Caption${i}` in source) return true;
    if (`Caption ${i}` in source) return true;
    if (`Description${i}` in source) return true;
    if (`Description ${i}` in source) return true;
    if (`caption_${i}` in source) return true;
    if (`spec_value_${i}` in source) return true;
  }
  return false;
}

function normalizeSpecificationsObject(value) {
  if (!value) return null;
  if (typeof value === "string") {
    try {
      const parsed = JSON.parse(value);
      return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : null;
    } catch {
      return null;
    }
  }
  if (typeof value === "object" && !Array.isArray(value)) return value;
  return null;
}

function hasSpecificationsJsonPayload(source) {
  if (!source || typeof source !== "object") return false;
  if ("specifications_json" in source || "specifications" in source) {
    const obj = normalizeSpecificationsObject(source.specifications_json ?? source.specifications);
    return Boolean(obj && Object.keys(obj).length);
  }
  return false;
}

function attributesFromSpecificationsJson(specificationsJson) {
  const obj = normalizeSpecificationsObject(specificationsJson) || {};
  const attrs = [];
  let sortOrder = 1;
  for (const [captionRaw, valueRaw] of Object.entries(obj)) {
    const caption = norm(captionRaw);
    if (!caption) continue;
    attrs.push({
      sort_order: sortOrder,
      caption,
      spec_value: valueRaw === null || valueRaw === undefined ? "" : String(valueRaw).trim(),
    });
    sortOrder += 1;
  }
  return attrs;
}

function specificationsJsonFromAttributes(attributes) {
  const out = {};
  for (const item of Array.isArray(attributes) ? attributes : []) {
    const caption = norm(item?.caption);
    if (!caption) continue;
    out[caption] = item?.spec_value === null || item?.spec_value === undefined ? "" : String(item.spec_value);
  }
  return out;
}

