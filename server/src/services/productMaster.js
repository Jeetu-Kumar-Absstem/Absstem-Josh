function mergeOxygenPackageAttributes(attributes, { itemCode, itemName, categoryName }) {
  if (!/^oxygen$/i.test(String(categoryName || "").trim())) return attributes;

  const packageData =
    OXYGEN_PACKAGE_BY_MODEL.get(normalizeOxygenModelKey(itemName)) ||
    OXYGEN_PACKAGE_BY_MODEL.get(normalizeOxygenModelKey(itemCode)) ||
    null;

  if (!packageData) return attributes;

  const next = Array.isArray(attributes) ? [...attributes] : [];
  const existing = new Set(next.map((item) => normalizeCaptionKey(item.caption)).filter(Boolean));
  const preferred = [
    { caption: "RECOMMENDED OXYGEN STORAGE", spec_value: `${packageData.storageVolume} L` },
    { caption: "RECOMMENDED AIR RECEIVER", spec_value: `${packageData.airVesselVolume} L` },
  ];

  for (const item of preferred) {
    if (existing.has(normalizeCaptionKey(item.caption))) continue;
    next.push({
      sort_order: next.length + 1,
      caption: item.caption,
      spec_value: item.spec_value,
    });
  }

  return next.map((item, index) => ({
    sort_order: index + 1,
    caption: norm(item.caption),
    spec_value: norm(item.spec_value),
  }));
}

