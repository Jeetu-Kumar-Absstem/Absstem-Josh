function buildUnifiedWorkbookRows(productRows = [], companyPolicyRows = []) {
  const productByItemCode = new Map(
    productRows
      .map((row) => [String(row.item_code || "").trim().toLowerCase(), row])
      .filter(([key]) => key)
  );
  const policyRowsByItemCode = new Map();
  for (const row of companyPolicyRows || []) {
    const key = String(row.item_code || "").trim().toLowerCase();
    if (!key) continue;
    if (!policyRowsByItemCode.has(key)) policyRowsByItemCode.set(key, []);
    policyRowsByItemCode.get(key).push(row);
  }

  const out = [];
  const usedProductCodes = new Set();

  for (const policyRow of companyPolicyRows || []) {
    const key = String(policyRow.item_code || "").trim().toLowerCase();
    const productRow = productByItemCode.get(key) || {};
    if (key) usedProductCodes.add(key);
    out.push({
      company: policyRow.company || "",
      item_code: productRow.item_code || policyRow.item_code || "",
      item_name: productRow.item_name || productRow.item_code || policyRow.item_code || "",
      category: productRow.category || "",
      group: productRow.group || "",
      uom: productRow.uom || "",
      hsn_no: productRow.hsn_no || "",
      gst_pct: productRow.gst_pct ?? "",
      list_price: productRow.list_price ?? "",
      active: productRow.active || "",
      serial_no_required: productRow.serial_no_required || "",
      auto_generated: productRow.auto_generated || "",
      brand: productRow.brand || "",
      item_type: productRow.item_type || "",
      family_key: productRow.family_key || "",
      module_role: productRow.module_role || "",
      variant_key: productRow.variant_key || "",
      description: productRow.description || "",
      sourcing_mode: policyRow.sourcing_mode || "",
      is_manufactured: policyRow.is_manufactured || "",
      mfg_job_prefix: policyRow.mfg_job_prefix || "",
      intercompany_source_company: policyRow.intercompany_source_company || "",
      preferred_vendor: policyRow.preferred_vendor || "",
      is_saleable: policyRow.is_saleable || "",
      is_purchaseable: policyRow.is_purchaseable || "",
      is_stocked: policyRow.is_stocked || "",
      remarks: policyRow.remarks || "",
      ...buildAttributeCellMap(productRow.attributes || productRow),
    });
  }

  for (const productRow of productRows || []) {
    const key = String(productRow.item_code || "").trim().toLowerCase();
    if (!key || usedProductCodes.has(key)) continue;
    out.push({
      company: "",
      item_code: productRow.item_code || "",
      item_name: productRow.item_name || productRow.item_code || "",
      category: productRow.category || "",
      group: productRow.group || "",
      uom: productRow.uom || "",
      hsn_no: productRow.hsn_no || "",
      gst_pct: productRow.gst_pct ?? "",
      list_price: productRow.list_price ?? "",
      active: productRow.active || "",
      serial_no_required: productRow.serial_no_required || "",
      auto_generated: productRow.auto_generated || "",
      brand: productRow.brand || "",
      item_type: productRow.item_type || "",
      family_key: productRow.family_key || "",
      module_role: productRow.module_role || "",
      variant_key: productRow.variant_key || "",
      description: productRow.description || "",
      sourcing_mode: "",
      is_manufactured: "",
      mfg_job_prefix: "",
      intercompany_source_company: "",
      preferred_vendor: "",
      is_saleable: "",
      is_purchaseable: "",
      is_stocked: "",
      remarks: "",
      ...buildAttributeCellMap(productRow.attributes || productRow),
    });
  }

  return out;
}

